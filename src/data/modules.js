export function getTotalStats(modules) {
  let totalQ = 0, totalAttempted = 0, totalCorrect = 0;
  for (const section of modules) {
    for (const mod of section.modules) {
      totalQ += mod.questions;
      totalAttempted += mod.attempted;
      totalCorrect += mod.correct;
    }
  }
  return { totalQ, totalAttempted, totalCorrect };
}

